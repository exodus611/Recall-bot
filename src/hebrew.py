import re

def parse(he_title: str, source_name: str) -> dict:
    """Извлекает из ивритского заголовка: причину, категорию, упомянутые бренды/продукт."""
    t = he_title
    reason_ru = None
    for pat, ru in REASONS:
        if re.search(pat, t):
            reason_ru = ru
            break
    category_ru, baby = "не определена", False
    for pat, ru, is_baby in CATEGORIES:
        if re.search(pat, t):
            category_ru, baby = ru, is_baby
            break
    brands = []
    for he, ru in BRANDS.items():
        if he in t:
            brands.append(ru)
    # товары в кавычках (ивритские/англ) — как в оригинале
    quoted = re.findall(r"[\u201c\u201d\"'\u05f4]([^\u201c\u201d\"'\u05f4]{2,40})[\u201c\u201d\"'\u05f4]", t)
    m = re.search(r"למוצר(?:י)?\s+([^\n•\-–|]{2,40})", t)
    if m and not quoted:
        quoted = [m.group(1).strip()]
    m2 = re.search(r"מוצרי\s+([A-Za-z0-9\u05d0-\u05ea][^\n•\-–|]{1,30})", t)
    if m2 and not quoted:
        quoted = [m2.group(1).strip()]
    return {
        "reason_ru": reason_ru,
        "category_ru": category_ru,
        "baby": baby,
        "brands": brands,
        "quoted": quoted,
        "official": ("gov.il" in source_name.lower()) or ("משרד הבריאות" in t),
    }
